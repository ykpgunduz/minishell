#include "mini.h"

void	free_s(char **s, int n)
{
	int	i;

	i = 0;
	if (!s)
		return ;
	while (s[i])
	{
		free(s[i]);
		i++;
	}
	free(s);
	if (n == 1)
		exit(1);
	else if (n == 0)
		exit(0);
}
